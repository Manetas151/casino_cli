BANNERS = {
    "win": WIN_BANNER,
    "lose": LOSE_BANNER,
    "draw": DRAW_BANNER,
}


def show_banner(kind: str, delay: float = BANNER_DELAY) -> None:
    art = BANNERS[kind]
    lines = art.strip("\n").split("\n")
    width = max(len(line) for line in lines)
    height = len(lines)

    left_pad = max(0, (SCREEN_COLS - width) // 2)
    top_pad = max(0, (SCREEN_ROWS - height) // 2)

    clear_and_home()
    print("\n" * top_pad, end="")
    for line in lines:
        print(" " * left_pad + line)

    time.sleep(delay)
